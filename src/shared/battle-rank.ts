// 胜利条件里的阈值。口径 wikiwiki「戦闘について」的勝敗判定表。
//
// 目前只有 A 胜这一条：它是唯一一个「算出来的」阈值（其余条件都是零受损、
// 敌旗舰沉、战果比 2.5× 这类直接判断），也因此是唯一会被两处各写一遍的。
// 回放侧（main/mg/battle.ts 的胜败预测）与显示侧（镝的胜负条件清单）此前
// 各自写了一份 `Math.floor(2 * n / 3)`，同一场仗的「预测 A」与「还差几艘到 A」
// 只要有一处改了口径就会自相矛盾。

/**
 * A 胜所需的击沉数：敌方**开战时存活**舰数的 2/3 向下取整。
 *
 * 注意这是「击沉数」的门槛，不含「我方无沉没」那一条——调用方另判。
 * 敌方只有一舰时 floor(2/3)=0，会把「一艘没沉」也算成达标；
 * 游戏里单舰编成没有 A 胜（打沉了就是 S），所以调用方要自己拦掉 n <= 1。
 */
export const requiredSunkForA = (enemyCount: number): number =>
  Math.floor((2 * enemyCount) / 3)
