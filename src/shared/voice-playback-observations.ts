/**
 * 正例：实测**音词相符**的形态。2026-08-23 开张。
 *
 * ---- 它不是装饰 ----
 * 把键逐格放回去的正路是「一格一证」，而证据有正有负。只收负例的台账会让人误以为
 * 「没被记下来的格都可疑」——而实际上玩家点得最多的那些格年年都对，只是没人写下来。
 * 这一份现在就被**护栏**消费：正例覆盖的形态，页面上必须真的有键——
 * 撤键那一刀如果哪天被谁顺手抹回来，这条会当场红。
 *
 * ⚠️ `slots` **只写玩家真的逐格听过的那几格**。他说「前几行」而没有逐格点名时，
 * 就留空、把范围如实写进 `scope`——把「大概都对」写成逐格证据，这份台账就没有价值了。
 */
export interface VoicePlaybackMatch {
  mstId: number
  observedAt: string
  /** 实测覆盖到哪儿。玩家没有逐格点名时，如实写他说的范围，别替他补全 */
  scope: string
  /** 逐格点名过的那几格。没点名就不写——留空不等于「全都对」 */
  slots?: readonly number[]
  /** 同一次实测里**对不上**的格（各自在 VOICE_PLAYBACK_OBSERVATIONS 里另有一条） */
  except?: readonly number[]
  evidence: string
}

