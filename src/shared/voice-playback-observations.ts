/**
 * 这一格有没有**负例**判例。有就一个键都不给，并给一句具体的说明，
 * 别让玩家以为是按钮坏了。正例不进这条查询——正例不改判据，只作证。
 */
export const voicePlaybackObservationAt = (
  mstId: number,
  slot: number | null | undefined,
): VoicePlaybackObservation | null => {
  if (slot == null) return null
  return (
    VOICE_PLAYBACK_OBSERVATIONS.find(
      (entry) => entry.mstId === mstId && entry.slot === slot,
    ) ?? null
  )
}

/** 这个形态有没有实测音词相符的正例。护栏据此钉住「这一页必须有键」。 */
export const voicePlaybackMatchOf = (mstId: number): VoicePlaybackMatch | null =>
  VOICE_PLAYBACK_MATCHES.find((entry) => entry.mstId === mstId) ?? null
