// 玩家**耳测**判例台账：点下播放钮，听到的与屏幕上写的对不对得上。**正反都收**。
//
// ---- 为什么要单独记 ----
// 这一类事只有耳朵能发现。包与包之间对得再齐，也证明不了「游戏此刻在那个地址上放的是哪一句」——
// 那是运营行为，随季节、随版本变。所以判据不能只靠数据自洽，得留一份**实测判例**：
// 谁、哪一格、哪一天、听到了什么、事后查出来那是什么。
//
// 范式照 `fit-bonus-corrections`（第一方修正台账）：条目是**人一条条写下来的**，
// 每条都带凭据与日期，任何人可据以复核。
//
// ---- 2026-08-23：这份台账从「只收翻车案」改成正反都收 ----
// 只记翻车的台账会把人引向一个错觉：**没被记下来的格子都是可疑的**。
// 实际反过来——玩家点得最多的那些格年年都对，只是没人把「对了」写下来。
// 于是这一版加了 `VOICE_PLAYBACK_MATCHES`：实测**音词相符**的形态也入账。
// 它不是装饰：把键逐格放回去的正路就是「一格一证」，而证据有正有负，
// 只收负例等于手里只有一半的证据链却要做全局判断。
//
// ============================================================================
// 撤键 → 恢复：2026-08-22 那一刀砍偏了，2026-08-23 精修
// ============================================================================
//
// 2026-08-22 因为下面两条负例，「整份字幕缺席的形态一律不给键」整档执行，撤下 2947 个键
//（自译层 2642 + 重归属层 305）。玩家看到島根丸整页 24 行全暗，提出质疑。重对证据轴后确认
// **那一刀砍的是错误的轴**：
//
//  · 国後（518）那一例的病根在 **kcwiki 台词表里有她音轨里根本不存在的行**——
//    她本地有 subtitle-ja（28 格），属于「有表可校验」的那一族；
//    而自译层覆盖的 76 个形态**没有一个**有 subtitle-ja（0/76），两个族在数据上不相交。
//    换句话说：那一例惩罚不到自译族。
//  · 島根丸（1003）那一例的文本与槽位映射**都是对的**——季节包里同一句的档名
//    `603-Sec1Seika2025` 是**游戏方自己的命名**，Sec1 就是 2 号槽。错的只是
//    「那个槽位当季装着季节版的音」。而**季节占槽是时间性的、对全站所有地址键一视同仁**：
//    key-confirmed 的键当季同样会播出季节音。拿它去惩罚某一族，族选错了。
//
// 于是 2026-08-23 把自译族与重归属族的键**按 wikiwiki 底本的 (形态, 槽位) 映射恢复**，
// 并把季节风险改成**全域一致的治理**（见下面「播放优先级」一节），不再按族歧视。
//
// ---- 但「wikiwiki 映射从没错过」这句话是假的，别写进任何地方 ----
// 恢复这一批时量过一次，结论如实记在这里，因为它是**已知残余风险**，不是脚注：
//
// 拿 wikiwiki 底本覆盖的 124 个形态里**本地有 subtitle-ja 表的那 45 个**做交叉校验
//（同一道 `foldVoiceLineForCompare`），逐行判「该槽对得上 / 这一句其实躺在该舰别的槽位 /
// 音轨里根本没这句」：
//
//   wikiwiki 底本（自译层的槽位来源）：可判 1748 行，对得上 1040、**错位 41**（2.35%）
//   kcwiki 档名（key-confirmed 的来源）：可判 9520 行，对得上 8507、**错位 2**（0.02%）
//
// 差一百倍，原因也清楚：kcwiki 的 key 就是**游戏自己的档名**（`106-Sec1`），
// 槽位是从音轨身份来的；wikiwiki 的槽位是从页面表格的「母港1 / 母港2」这类**展示序**推的。
//
// 那 41 例逐条查过病因，真正该算在「映射不可信」头上的只有一半：
//   ① **13 例**：wikiwiki 把同一句重复列在两个场合（游戏早年一份档案兼两个场合，后来拆开了）
//      ——表本身没错，是上游拆分后 wiki 的合并展示过时了；
//   ② **4 例**：表推那一格此刻被季节语音占着（島根丸同族），映射没被证伪；
//   ③ **20 例 / 7 个形态**：真·成对互换（母港1↔母港2、装備1↔装備2、小破↔旗艦大破），
//      这才是「wiki 的场合编号与游戏槽位顺序不一致」；
//   ④ 其余 4 例查不出，如实留着。
// 校正后的「映射不可信」率是 **20/1748 = 1.14%**，集中在 7/45 个形态上。
//
// **逐槽的错位率（下次有人报播错句时，这就是排查顺序）**：
//   秘书舰1(2) 36.4% · 出撃(14) 26.3% · 秘书舰2(3) 26.1% · 婚后母港(28) 10.0% ·
//   小破2(20) 8.8% · 秘书舰3(4) 8.7% · 小破1(19) 8.3% · 补给(27) 7.1% · 夜战(17) 6.5% ·
//   装备(9/10) 约 3% —— **其余 40 个槽位（全部 24 格时报、图鉴介绍、结婚、击沉、MVP……）实测 0 错位**。
// 自译层 2642 行里落在「出现过错位的槽位」上的是 671 行（25.4%）。
//
// 那 41 例里的 ① 型在自译层能机械查出来：**同一句被列在两个场合**的行共 12 行 / 6 个形态
//（编成↔出征、小破1↔小破2 这种相邻场合）。它们至多有一处对得上，但失败模式是
// 「听到她自己相邻场合的另一句」，与本域另一头的「整页全暗」相比是轻得多的代价，故不额外撤键，
// 只在这里留底备查。
//
// ---- 为什么明知有 1.14% 仍然把键放回去 ----
// 因为对照的另一头不是「零风险」，是**整页 24 行全暗**——那是玩家当场否掉的形态，
// 而且它把一整层做对了的东西也一起关掉了。失败模式也不同级：
// 错位听到的是**她自己**相邻场合的另一句，不是别人的话。
// 唯一一次真正落在自译族形态上的耳测（島根丸）给的还是**正例**：除 2 号槽外各行音词相符。
// 收紧的正路是**一格一证**（这份台账），不是把整族的闸门拧死。
//
// ---- 播放优先级：档案实听实物 > 地址现取（2026-08-23 落地，全域一致）----
// 玩家在游戏里真的听到过那一格，`renderer/voice-archive` 就留下了那一份实物。
// 那时这一格的播放钮播的是**他自己听到过的那一份**，天然不会错句——
// 既不受季节换文件影响，也不受映射错位影响。所以判据是：
//   ① 这一格有耳测**负例** → 一个键都不给（本文件的 `VOICE_PLAYBACK_OBSERVATIONS`）；
//   ② 档案里有这一格的实物 → 播实物；
//   ③ 否则按地址现取。
// 这条**对所有键一视同仁**，不分 key-confirmed / wikiwiki-mapped——
// 季节占槽本来就是时间性的、对谁都一样，按族歧视是上一版的错。
// 与立绘卷、季节台词卷的「点亮式」同构：**没见过的不假装有，见过的才点亮**。

export interface VoicePlaybackObservation {
  /** 出问题的那个形态（玩家当时看的那一页） */
  mstId: number
  /** 表推给出的槽位——**它通常是对的**，错的是这个槽位当时装着什么 */
  slot: number
  /** 玩家实测的日期（本机时区的日历日） */
  observedAt: string
  /** 界面上当时显示的那一句（我们以为会播的） */
  expected: string
  /** 玩家实际听到的那一句，事后查出来的出处 */
  heard: string
  /**
   * 判定。`season-slot` = 那个槽位当季被季节语音占着（官方换文件，过季换回）；
   * `slot-offset` = 该舰的槽位排布与统计先验不一致；`unknown` = 查不出来，如实记。
   */
  verdict: 'season-slot' | 'slot-offset' | 'unknown'
  /** 凭据：怎么查出来的。写得出档名就写档名，写不出就写「查不到」 */
  evidence: string
  /**
   * `season-slot` 专用：**此刻挂在那个槽位上的**是季节台词包里的哪一条（档名）。
   *
   * 有这一项就意味着「我们知道那个地址现在放的是哪一句」——于是两件事可以做：
   *  ① 常规行的悬停从「播的是另一句」升级成**指路**（去下面的季节栏看那一条）；
   *  ② 那一条**季节行本身可以给键**：点下去播的正是它，不是错句。
   *
   * ⚠️ 这一项**只由证据授予，不由推断授予**。不做「按今天的日期猜当季」那种全局推断——
   * 官方换文件的时点、哪些舰参与、换的是哪一句，都不是日历能算出来的。
   * 一格一证，没有证据的季节行照旧只认档案实物（点亮式）。
   */
  mountedSeasonalKey?: string
}

