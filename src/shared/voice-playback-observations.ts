/**
 * 「有语音、没有台词」的**补词工作队列**。
 *
 * ---- 这是个要填的坑，不是要遮的丑 ----
 * 用户 2026-08-22 的原话大意：「『有语音没有台词』这个状态最好不要存在」——
 * 指的是**不要存在这种情况**（一段语音没人配词），不是「不要存在键配无词这种搭配」。
 * 所以消灭它的方式是**把词补上来**（字幕补录 / wikiwiki 转写 / 艦素自译三条渠道），
 * **不是把播放钮撤下去**。撤键治的是另一种病（播错句），两件事不能混。
 *
 * 词到之前的过渡态是**诚实的空**：实时字幕在拿不到词时一条都不出
 *（`renderer/voice-subtitle` 三处 `if (!text) return []`），宁可没有字幕，
 * 也绝不显示一句对不上的词。图鉴那边同理——缺格不写抱怨文案。
 *
 * ---- 这份名单从哪来 ----
 * 运行时的 `voice-unmatched.json` 台账逐条记着「游戏请求过、本地没有词」的格
 *（`main/voice-diagnostics` 的 `no-text` 一档）。那是**每台机器各自**的观测，
 * 不入仓；这里抄的是 2026-08-22 本机那一份里 `kind === 'ship'` 的部分，
 * 作为**已知待补**的起点，供后续批次照着补。补掉一格就从这里划掉一格。
 */
