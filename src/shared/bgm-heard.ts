// 曲名的**第一方耳测层**（2026-08-24 起）。两棵树各一张表：
// 战斗树 `HEARD_BGM_NAMES`（本文件主体），母港树 `HEARD_PORT_BGM_NAMES`（见下方）。
// 下面这段讲的是战斗树为什么非它不可；母港树的理由另写在那张表头上。
//
// ## 为什么非它不可
//
// 战斗树的曲名，**游戏一个字都不发**——这是穷举出来的，不是猜的：
// 21 天真账本 15306 条有 body 的报文里，97 首已知战斗曲名出现次数为 0；
// 全部带 bgm 字样的字段只有五个（`api_bgm` 是音量滑条、`api_p_bgm_id` 与
// `api_mst_furniture.api_bgm_id` 指母港树、`api_mst_bgm` 是母港曲名表、
// `api_mst_mapbgm` 只给战斗树的号不给名）。所以任何被动配对方案至多得到
// 「场景 → 号」，永远得不到「号 → 名」；蓄音机那条路也不通（它设的是**母港**曲，
// 而母港号本来就等于主数据 id、早有名字）。
//
// 拆包层（矿脉包 `kcwiki-bgm`）按游戏原文件名键入，覆盖了 97 个号，但它对
// 战斗树 1–99 那批常规海域老曲基本没收——站方对那些只留了自己的上传序号。
// 剩下的缺口只剩一条路：**人去听**。
//
// ## 这一层的证据强度
//
// 每一条都是提督在自己的客户端里**亲耳听**那个编号的音轨确认的
// （鉴 → 海域卷 → 该图详情 → BGM 行点 ♪，放的就是该编号当前的实际音轨；
// 试听地址由 `createCipher` 现算，与拆包页记下的游戏原文件名逐位相同，
// 133/149/150/190/275/132 六个号全中，所以听到的确实是那个号）。
//
// 这是**一手证据**：比任何社区表格都硬。但它仍排在拆包层之后，
// 理由不是不信人，而是拆包层的键是游戏自己的文件名、中间没有人的判断；
// 两层真撞上时**不静默覆盖**，挂出来单独裁（目前零重叠，见测试）。
//
// **「没有人的判断」只对得上一半，2026-08-24 当场吃过一次亏**：号确实是从游戏原文件名
// 读出来的，但**曲名那一格是站方编辑照官方曲目表手打的日文，会打错**——124 号写成了
// 「決戦！北太平洋」，官方原名是「決戦！北大西洋」（太/大 差一笔，差一整个大洋）。
// 修正走 scripts/lib/kcwiki-bgm.mjs 的 KNOWN_TRANSCRIPTION_FIXES 台账（带指纹核对）。
// 所以拆包层排在前面的正确说法是：**它的号可靠，名字仍是转写**；
// 遇到官方一手曲目表（OST 曲目表 / 運営 推文）时，那才是曲名的最终出处。
//
// ## 维护方式
//
// 提督报一条收一条，逐条带 `heardAt`。判不准的、要重听的**不写**——
// UI 自动回退成编号，宁可只报号也不编。名字一律用日文官方曲名原文
// （曲名是作品名称，不翻译）。

export interface HeardBgmName {
  /** 资源号（`/kcs2/resources/bgm/<树>/NNN_XXXX.mp3` 的 NNN；两棵树各自一套号） */
  id: number
  /** 官方曲名（日文原文） */
  name: string
  /** 亲历确认的日期 */
  heardAt: string
  /** 提督随口补的履历/来路，只给维护者看，不进 UI */
  note?: string
}

