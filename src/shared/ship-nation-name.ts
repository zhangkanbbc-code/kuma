// 编成门标签里的**国籍词组**统一写法（2026-09-01 起）。
//
// ---- 为什么还要第三遍 ----
// 舰种词（`ship-type-name.ts`）与专有名词（`ship-proper-name.ts`）两遍跑完，
// 编成门这一列还剩最后一族并排的说法——国籍组：
//   · 艦素**手写**规则里写的是「美/英/澳/荷舰娘」「法国舰娘」；
//   · 同一批任务的**自研推导**侧把中文正文原样切下来当 label，正文写什么就是什么：
//     「美英澳荷出身的舰娘」「美英澳荷出身舰娘」「美英舰艇」「法国舰艇」「法国船」。
// 于是同一个概念五种写法，中心词还分「舰娘 / 舰艇 / 船」三种。
// 用户 2026-09-01 拍板：「国籍词可以改成舰娘」。
//
// ---- 与 `shared/ship-nationality.ts` 的分界 ----
// 那一份是 EO 国籍编号（id / key / label / aliases）的本地镜像，供**判定**用（谁是法国舰）；
// 这一份只管**上屏那几个字**，不认舰、不判国籍、一个 id 都不碰。两者没有调用关系。
//
// ---- 不新造词 ----
// 表里的值逐个有出处，全部照抄艦素手写规则 `kanso-quest-rules.ts` 里已有的 label：
//   · 「美/英/澳/荷舰娘」＝ B149 / B150 手写标签逐字；
//   · 「法国舰娘」＝ Cy14 手写标签逐字；
//   · 「美/英舰娘」是前两条的构词法（国籍简称用「/」并列 + 中心词「舰娘」）套在 By11 的
//     「美英」上——「美/英」这个并列写法本身也是手写标签里现成的（B151「美/英航空母舰」）。
// 国籍**少了或多了一个**都是在改门的说法，所以只换中心词与连接写法，国籍一个不动。
//
// ---- 只换中心词是「舰艇 / 船」的那几条 ----
// 「美军(USS)舰娘」原样保留：中心词已经是「舰娘」，而「(USS)」是**中文正文自己带的括注**
// （B147），删掉就是替正文改口。
// 「美/英航空母舰」同样保留：那里的中心词是**舰种词**「航空母舰」而不是国籍后缀，
// 换成「舰娘」会把「只要美英航母」说成「只要美英舰」——门变松，是硬伤方向。
//
// ---- 闭合表 + 整词精确匹配 ----
// **不做子串替换**：「舰艇」两个字在别处也会出现（舰种词、队名残段、地名），
// 拿它做子串替换迟早误伤。表里没有的词组一个字节都不动——最坏退回今天的混排。
// 上游冒出新变体时护栏当场红（判据取 `quest-fleet-rules` 的国籍词典与中心词表，
// 不是这张表自己），修法是补一格，不是让混排悄悄回来。
import { mapLabelWords } from './ship-type-name'

/**
 * 国籍词组 → 规范中文写法。**封闭表**，键是自研推导侧真实产出过的写法。
 *
 * 值等于键的两条照样列出来（同 `ship-type-name.ts` 的纪律）：
 * 「这个词组已经核过、就是规范写法」与「这个词组还没人管过」是两回事，
 * 留白会让下一个人以为漏了。
 *
 * 「美/英/澳/荷舰娘」与「美/英航空母舰」**进不了这张表**——「/」是切词的分隔符，
 * 它们到出口时早被切成「美」「英」「澳」「荷舰娘」这样的段，永远不会整词命中。
 * 它们本就是规范写法，不进表也不用管；护栏那一条按**整条标签**收，钉住的正是它们。
 */
export const NATION_LABEL_ZH: Record<string, string> = {
  // ---- 自研推导侧从中文正文切下来的写法 ----
  美英澳荷出身的舰娘: '美/英/澳/荷舰娘', // B148、B149
  美英澳荷出身舰娘: '美/英/澳/荷舰娘', // B150
  美英舰艇: '美/英舰娘', // By11
  法国舰艇: '法国舰娘', // 2606Cw1
  法国船: '法国舰娘', // Cy14（同一条任务的手写侧写的就是「法国舰娘」）
  // ---- 已经是规范写法的，列出来当账 ----
  法国舰娘: '法国舰娘', // Cy14 手写标签
  '美军(USS)舰娘': '美军(USS)舰娘', // B147，括注是中文正文自己带的
}

/**
 * 编成门标签的国籍词组规范写法。**整词匹配**：表里有就换，没有就原样放行。
 *
 * 切法与前两遍同源（`mapLabelWords`），词前后的空白与分隔符一个字节都不碰。
 *
 * 与前两遍的先后：**放在最后一遍**。理由不是随手排的——
 * 前两遍会把日/繁字形折成简体（`法国艦艇` → `法国舰艇`），
 * 折完再查这张表，一张表就够收两种字形；反过来排，表里得给每种字形各备一格。
 * 而它自己的产物带着「/」（`美/英/澳/荷舰娘`），放最后就不会再被谁切开重读。
 */
export const localizeShipNationWords = (label: string): string =>
  mapLabelWords(label, (word) => NATION_LABEL_ZH[word])
