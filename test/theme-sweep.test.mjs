  test(name + ' 样式声明中不再有根块外十六进制颜色（仅纯黑阴影豁免）', () => {
    const found = []
    for (const rule of outsideRoots(read(name)).matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      for (const declaration of rule[2].split(';')) {
        const colon = declaration.indexOf(':')
        if (colon < 0) continue
        const property = declaration.slice(0, colon).trim()
        const value = declaration.slice(colon + 1)
        for (const color of value.matchAll(/#[0-9a-fA-F]{3,8}\b/g)) {
          if (/^(text-shadow|box-shadow)$/.test(property) && color[0] === '#000') continue
          found.push(rule[1].trim() + ' / ' + property + ': ' + color[0])
        }
      }
    }
    assert.deepEqual(found, [])
  })

