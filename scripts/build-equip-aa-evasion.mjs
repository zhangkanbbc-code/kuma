#!/usr/bin/env node
// 生成《装备对空射击回避事实表》——第一方随包资料包。
//
// 这是**合成器，不是日常工序**：往后维护直接改 assets/lodes/equip-aa-evasion.json，
// 或者改本文件下面那张台账再重跑。跑法：
//   node scripts/build-equip-aa-evasion.mjs
//
// ── 这张表记的是什么 ───────────────────────────────────────────────
// 有些机体挨敌方对空射击时更不容易被打下来。游戏把它做成两个补正系数，
// 分别乘在敌方的「加重対空値」与「艦隊防空値」上：
//     加重対空値(補正後) = [加重対空値 × 加重対空補正]
//     艦隊防空値(補正後) = [艦隊防空値 × 艦隊防空補正]
// 综合评价分五档，高到低是 ❀ > ☆ > ◎ > ◯ > △。
//
// ── 为什么是第一方表而不是自取包 ─────────────────────────────────
// 与 equip-improve 同一套法理：**哪件机体吃哪个补正是游戏机制的客观事实**，
// 由游戏决定，不属于任何转录者；攻略站是把事实抄下来的人，不是事实的来源。
// 所以 schema 是我们的、取舍是我们的、每条带 basis 写明置信等级，随源码分发。
// 只誊事实三列（两个补正 + 档位符号），**不搬**上游那张表的分类列与备注列
// （「夜攻」「対潜値7超」「対地艦爆」那些是编辑者的解说，不是这张表要答的问题）。
//
// ── 置信度：整张表都是「单源待印证」，别当官方数值用 ───────────────
// 官方从未公布这些系数，它们是社区验证出来的。本次取证 2026-08-27：
// 上游表最终更新 2026-08-17，47 行机体名**全部**能在游戏主数据 api_mst_slotitem
// 里按名字对上（0 条落空）——这只证明誊抄没串行，不证明数值对。
// 同站「一式陸攻(野中隊)」页对 170 这一条给了同样的 0.6/1.0 并称之为「弱補正」，
// 但那是同一个 wiki，算同源转录不算第二票。真要升格得靠账本实测或独立验证。
//
// ⚠️ **「不在表里」不等于「弱档」**：一式陸攻、銀河(无印)、四式重爆 飛龍(无印)、
// 深山、東海、二式大艇 等等都不在上游表里，它们是**无档**（补正 1.0/1.0，即不减免）。
// 显示层必须把「无档」与「△ 弱档」分开说，别把没查到写成最低档。

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = process.env.KANSO_AA_EVASION_OUT || path.join(ROOT, 'assets', 'lodes', 'equip-aa-evasion.json')

/** 上游表的最终更新日（誊抄当时）——记进 meta，不是给玩家看的 */
const UPSTREAM_UPDATED_AT = '2026-08-17'
const TRANSCRIBED_AT = '2026-08-27'

/**
 * 台账：[装备主数据 id, 加重対空補正, 艦隊防空補正, 档位符号]
 * 顺序照上游表的分节顺序（艦攻→艦爆→噴式→水爆→対潜哨戒→陸攻→全翼），
 * 只为人工比对方便；消费端一律按 id 查表，不依赖顺序。
 */
const LEDGER = [
  // 艦上攻撃機
  [143, 0.6, 1, '△'], [144, 0.6, 1, '△'], [93, 0.6, 1, '△'], [94, 0.6, 1, '△'],
  [374, 0.6, 1, '△'], [545, 0.6, 1, '△'], [466, 0.6, 1, '△'], [343, 0.6, 1, '△'],
  [570, 0.6, 0.7, '◯'], [559, 0.6, 1, '△'], [481, 0.6, 1, '△'],
  // 艦上爆撃機
  [99, 0.6, 1, '△'], [100, 0.6, 0.7, '◯'], [319, 0.6, 1, '△'], [320, 0.6, 1, '△'],
  [557, 0.6, 1, '△'], [558, 0.6, 0.7, '◯'], [154, 0.6, 0.7, '◯'], [487, 0.6, 1, '△'],
  [474, 0.6, 1, '△'], [475, 0.6, 1, '△'], [476, 0.6, 1, '△'],
  // 噴式戦闘爆撃機
  [199, 0.5, 0.7, '◎'], [200, 0.5, 0.5, '☆'],
  // 水上爆撃機
  [79, 0.6, 1, '△'], [80, 0.6, 1, '△'], [81, 0.6, 0.7, '◯'], [237, 0.6, 0.7, '◯'],
  [322, 0.5, 0.7, '◎'], [490, 0.5, 0.7, '◎'], [323, 0.5, 0.5, '☆'], [208, 0.6, 1, '△'],
  // 対潜哨戒機
  [491, 0.6, 1, '△'],
  // 陸上攻撃機
  [170, 0.6, 1, '△'], [504, 0.6, 1, '△'], [388, 0.6, 1, '△'], [224, 0.6, 0.7, '◯'],
  [404, 0.6, 1, '△'], [444, 0.6, 1, '△'], [484, 0.6, 1, '△'], [453, 0.6, 1, '△'],
  [454, 0.6, 0.7, '◯'], [405, 0.6, 1, '△'], [406, 0.6, 1, '△'], [433, 0.6, 1, '△'],
  [479, 0.6, 0.7, '◯'],
  // 全翼型戦闘爆撃機
  [561, 0.4, 0.4, '❀'],
]

const BASIS = `整理参照 · 单源待印证 ${UPSTREAM_UPDATED_AT}`

const data = LEDGER.map(([eqId, weighted, fleet, tier]) => ({
  eq_id: eqId,
  weighted_aa: weighted,
  fleet_aa: fleet,
  tier,
  basis: BASIS,
}))

// id 不许重复：台账是手抄的，重复项会让后写的那条静默顶掉前一条
const seen = new Set()
for (const row of data) {
  if (seen.has(row.eq_id)) throw new Error(`台账里 eq_id ${row.eq_id} 出现了两次`)
  seen.add(row.eq_id)
}

const existing = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : null

const pack = {
  meta: {
    id: 'equip-aa-evasion',
    name: '装备对空射击回避事实表（第一方）',
    version: `${TRANSCRIBED_AT.replace(/-/g, '.')}`,
    source: 'kuma 对空射击回避事实表（第一方整理）',
    // 内容没变就不动时间戳——幂等，重跑不产生假的「刚更新」
    fetchedAt: existing?.meta?.fetchedAt ?? new Date().toISOString(),
    upstreamUpdatedAt: UPSTREAM_UPDATED_AT,
    license:
      '第一方事实表：记的是游戏机制的客观事实（各机体挨敌方对空射击时的减免补正），随源码分发',
    note: '舰载机的对空射击回避档位',
    maintainerNote: [
      '事实来源是游戏本身；整理时参照过公开验证资料，逐条与游戏主数据对名核过（47/47 全部命中，0 条落空）。',
      '两个补正分别乘在敌方的加重対空値与艦隊防空値上；综合档位高到低为 ❀ > ☆ > ◎ > ◯ > △。',
      `置信度：**整张表都是单源待印证**（上游表最终更新 ${UPSTREAM_UPDATED_AT}，誊抄于 ${TRANSCRIBED_AT}）。` +
        '官方从未公布这些系数，它们是社区验证的产物。同站的逐机页对 170 给了一样的 0.6/1.0 并称「弱補正」，' +
        '但同站不算第二票（同源转录）。要升格得靠账本实测或真正独立的验证。',
      '**不在表里 ≠ 弱档**：一式陸攻、銀河(无印)、四式重爆 飛龍(无印)、深山、東海、二式大艇 等都不在上游表里，' +
        '它们是无档（1.0/1.0，不减免）。消费端必须把「无档」和「△ 弱档」分开显示，别把没查到写成最低档。',
      '只誊事实三列，上游那张表的分类列与备注列（夜攻／対潜値7超／対地艦爆 之类）是编辑者的解说，不誊。',
      '维护直接改这张表，或改 scripts/build-equip-aa-evasion.mjs 的台账后重跑（幂等，内容没变不动 fetchedAt）。',
    ],
  },
  data,
}

const next = `${JSON.stringify(pack, null, 2)}\n`
const prev = existing ? `${JSON.stringify(existing, null, 2)}\n` : null
// 只比内容，不比 fetchedAt：内容一致就一个字节都不写
if (prev && JSON.stringify(existing.data) === JSON.stringify(pack.data)) {
  console.log(`内容未变，未改动 ${path.relative(ROOT, OUT)}（${data.length} 条）`)
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, next, 'utf8')
  console.log(`已写出 ${path.relative(ROOT, OUT)}：${data.length} 条`)
}
